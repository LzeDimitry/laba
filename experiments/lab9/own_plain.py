"""ЛР9: власна програма перевірки контрольного значення (прозора версія).

Використовується як еталон для порівняння складності аналізу з
обфускованою версією (own_protected.py).
"""

CONTROL = "2026_KBZI-24-2_Tovt_Rastislav_варіант:01"


def main() -> None:
    value = input("Введіть контрольне значення: ")
    if value == CONTROL:
        print("Контрольне значення збігається")
    else:
        print("Контрольне значення не збігається")


if __name__ == "__main__":
    main()
